export function buildUserPrompt(text: string): string {
  return `下面是一句现代中文。请把这句话本身翻译成新三国台词风格，直接输出译文。

任务定义（务必遵守）：
- 这句话就是台词原材料。你只是把它"换一种说法"，用新三国口吻和词汇重新表达。
- 不要把它当成"有人对你说了这句话"而去回应、反驳或发飙。
- 保留原句的核心意思，不要跑题，不要写成与原文无关的长篇独白。
- 各种角色的经典梗都可以随手化用，让风味更足。

错误示范：
- 输入"你能帮我一个忙吗" → 错误：听完请求后的独白（"你竟敢向孤开口？不可能！绝对不可能！"）
- 正确：用新三国口吻请人帮忙（"汝且道来，这忙某家帮是不帮。"）

原文：
${text}`;
}

